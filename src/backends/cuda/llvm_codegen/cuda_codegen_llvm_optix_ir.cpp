luisa::string luisa_compute_cuda_llvm_encode_optix_ir(
    luisa::span<const std::byte> bitcode, uint32_t cuda_arch) noexcept {
    constexpr std::array<uint8_t, 4u> bitcode_magic{0x42u, 0x43u, 0xc0u, 0xdeu};
    LUISA_ASSERT(bitcode.size() >= bitcode_magic.size(), "Missing LLVM bitcode for OptiX IR.");
    for (auto i = 0u; i < bitcode_magic.size(); i++) {
        LUISA_ASSERT(std::to_integer<uint8_t>(bitcode[i]) == bitcode_magic[i],
                     "OptiX IR requires raw LLVM bitcode.");
    }
    LUISA_ASSERT(cuda_arch != 0u && cuda_arch <= 0xffffu / 10u,
                 "CUDA architecture is outside the OptiX IR container's scalar range.");
    constexpr auto scalar_fields_end = 44u;
    constexpr auto payload_offset = 48u;
    LUISA_ASSERT(bitcode.size() <= std::numeric_limits<size_t>::max() - payload_offset,
                 "OptiX IR container size overflow.");
    luisa::vector<std::byte> output;
    output.reserve(payload_offset + bitcode.size());
    auto append_u16 = [&output](uint16_t value) noexcept {
        output.emplace_back(static_cast<std::byte>(value & 0xffu));
        output.emplace_back(static_cast<std::byte>((value >> 8u) & 0xffu));
    };
    auto append_u32 = [&output](uint32_t value) noexcept {
        for (auto i = 0u; i < 4u; i++) {
            output.emplace_back(static_cast<std::byte>((value >> (i * 8u)) & 0xffu));
        }
    };
    append_u32(0x7f4e43edu);
    for (auto value : std::array<uint8_t, 8u>{0x01u, 0x43u, 0x02u, 0x73u, 0x03u, 0x02u, 0x07u, 0x00u}) {
        output.emplace_back(static_cast<std::byte>(value));
    }
    append_u16(24u);
    append_u16(2u);
    append_u32(scalar_fields_end);
    append_u32(payload_offset);
    append_u16(1u);
    append_u16(static_cast<uint16_t>(cuda_arch * 10u));
    append_u16(2u);
    append_u16(0u);
    append_u16(3u);
    append_u16(0u);// The host LLVM pipeline has already optimized the module.
    append_u16(99u);
    append_u16(0u);
    append_u16(0u);
    append_u16(0u);

    auto seed = 2166136261u;
    for (auto value : bitcode) {
        seed ^= std::to_integer<uint8_t>(value);
        seed *= 16777619u;
    }
    if (seed == 0u) { seed = 1u; }
    append_u32(seed);
    LUISA_ASSERT(output.size() == payload_offset, "Invalid OptiX IR container header size.");
    auto feedback = static_cast<uint8_t>(~seed);
    auto key = 0u;
    auto key_bytes_left = 1u;
    for (auto value : bitcode) {
        if (--key_bytes_left == 0u) {
            seed = seed * 0x41c64e6du + 0x3039u;
            key = seed;
            key_bytes_left = 4u;
        } else {
            key >>= 8u;
        }
        feedback ^= kNvvmForwardSubstitution[std::to_integer<uint8_t>(value) ^ static_cast<uint8_t>(key)];
        output.emplace_back(static_cast<std::byte>(feedback));
    }
    return {reinterpret_cast<const char *>(output.data()), output.size()};
}

