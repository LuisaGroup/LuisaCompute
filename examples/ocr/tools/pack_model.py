#!/usr/bin/env python3
"""pack_model.py -- stream an official checkpoint into a .lcocr v1 package.

Offline tool. Reads safetensors shards through `safetensors.safe_open` (lazy,
per-tensor) so an entire multi-gigabyte model is NEVER held in one host
dictionary. Canonicalizes names, optionally transposes linear weights to
[K, N], and quantizes eligible tensors to grouped INT4/INT8 -- only when
explicitly requested and mathematically valid. Writes the SAME v1 format the
C++ reader (examples/ocr/ocr/package.cpp) validates.

No network access. The official config/reference code and the checkpoint
revision/license must be supplied explicitly; nothing is downloaded.

This tool requires `safetensors` and `numpy` for real checkpoints. The frozen
synthetic fixtures are generated by the standard-library-only path in
src/tests/data/ocr (see golden_manifest.json), not by this tool.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lcocr_format import (  # noqa: E402
    ENCODING_BF16,
    ENCODING_FP16,
    ENCODING_FP32,
    ENCODING_INT4_PACKED,
    ENCODING_INT8,
    LAYOUT_KN,
    LAYOUT_ROW_MAJOR,
    QUANT_INT4_ASYMMETRIC,
    QUANT_INT4_SYMMETRIC,
    QUANT_INT8_SYMMETRIC,
    QUANT_NONE,
    FormatError,
    group_count,
    pack_int4_codes,
)
from lcocr_writer import PackageWriter  # noqa: E402


def _die(msg: str) -> "NoReturn":  # type: ignore[name-defined]
    print(f"pack_model: error: {msg}", file=sys.stderr)
    raise SystemExit(2)


def _sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _require_local_file(path: str, what: str) -> str:
    if not path:
        _die(f"{what} is required (offline tool; no implicit download)")
    if not os.path.isfile(path):
        _die(f"{what} not found: {path}")
    return path


def _load_official_config(config_path: str) -> dict:
    with open(config_path, "r", encoding="utf-8") as f:
        config = json.load(f)
    if not isinstance(config, dict):
        _die("official config must be a JSON object")
    return config


def _quantize_int4(values, group_size: int, symmetric: bool):
    """Grouped INT4 quantization matching quantization.cpp (RNE, min/max)."""
    import numpy as np

    flat = np.asarray(values, dtype=np.float32).reshape(-1)
    if not np.all(np.isfinite(flat)):
        raise FormatError("cannot quantize non-finite values")
    n = flat.size
    groups = group_count(n, group_size)
    codes = np.zeros(n, dtype=np.uint8)
    scales = np.ones(groups, dtype=np.float32)
    zero_points = np.full(groups, 8, dtype=np.uint8)
    for g in range(groups):
        begin = g * group_size
        end = min(n, (g + 1) * group_size)
        block = flat[begin:end]
        lo = float(min(0.0, float(block.min())))
        hi = float(max(0.0, float(block.max())))
        scale = 1.0
        zp = 8
        if symmetric:
            max_abs = max(abs(lo), abs(hi))
            if max_abs > 0.0:
                scale = max(max_abs / 7.0, max_abs / 7.5)
        else:
            rng = hi - lo
            if rng > 0.0:
                scale = max(rng / 15.0, rng / 15.5)
                zp = int(np.clip(np.rint(-lo / scale), 0, 15))
        if not (scale > 0.0) or not np.isfinite(scale):
            scale, zp = 1.0, 8
        scales[g] = scale
        zero_points[g] = zp
        q = np.clip(np.rint(block / scale + zp), 0, 15).astype(np.uint8)
        codes[begin:end] = q
    packed = pack_int4_codes(codes.tolist())
    zp_list = zero_points.tolist() if not symmetric else []
    return packed, scales.tolist(), zp_list


def _quantize_int8(values, group_size: int):
    import numpy as np

    flat = np.asarray(values, dtype=np.float32).reshape(-1)
    if not np.all(np.isfinite(flat)):
        raise FormatError("cannot quantize non-finite values")
    n = flat.size
    groups = group_count(n, group_size)
    codes = np.zeros(n, dtype=np.int8)
    scales = np.ones(groups, dtype=np.float32)
    for g in range(groups):
        begin = g * group_size
        end = min(n, (g + 1) * group_size)
        block = flat[begin:end]
        max_abs = float(np.max(np.abs(block))) if block.size else 0.0
        scale = 1.0
        if max_abs > 0.0:
            scale = max(max_abs / 127.0, max_abs / 127.5)
        if not (scale > 0.0) or not np.isfinite(scale):
            scale = 1.0
        scales[g] = scale
        codes[begin:end] = np.clip(np.rint(block / scale), -127, 127).astype(np.int8)
    return codes.tobytes(), scales.tolist()


def _fp32_to_fp16_bytes(values) -> bytes:
    import numpy as np

    return np.asarray(values, dtype=np.float16).tobytes()


def _fp32_to_bf16_bytes(values) -> bytes:
    import numpy as np

    f32 = np.asarray(values, dtype=np.float32)
    bits = f32.view(np.uint32).copy()
    # NaN must stay NaN: the RNE add below could carry a NaN payload into the
    # exponent and turn it into infinity. Handle NaN explicitly (quiet it and
    # keep a nonzero payload), matching the C++ fp32_to_bf16.
    nan_mask = (bits & 0x7F800000) == 0x7F800000
    nan_mask &= (bits & 0x007FFFFF) != 0
    if np.any(nan_mask):
        upper = (bits >> 16) | 0x0040
        # Ensure a nonzero mantissa so the result is not infinity.
        upper = np.where((upper & 0x007F) == 0, upper | 0x0001, upper)
        bits = np.where(nan_mask, upper << 16, bits)
    # RNE on the low 16 bits for non-NaN values (inf/zero pass through).
    lsb = (bits >> 16) & 1
    rounded = bits + 0x7FFF + lsb
    out = (rounded >> 16).astype(np.uint16)
    # Restore the explicit NaN results (the add must not alter them).
    if np.any(nan_mask):
        out = np.where(nan_mask, (bits >> 16).astype(np.uint16), out)
    return out.tobytes()


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="pack_model.py",
        description="Stream an official safetensors checkpoint into a .lcocr v1 package (offline).",
    )
    p.add_argument("--checkpoint-dir", required=True,
                   help="Local directory holding the official safetensors shards (no download).")
    p.add_argument("--config", required=True,
                   help="Local official config.json (identity/fingerprint source).")
    p.add_argument("--revision", required=True,
                   help="Exact official checkpoint revision (recorded, not fetched).")
    p.add_argument("--license", required=True,
                   help="SPDX license identifier of the checkpoint (validated non-empty).")
    p.add_argument("--model", required=True,
                   help="Semantic model target selector, e.g. glm_ocr or pp_ocrv6:medium.")
    p.add_argument("--recipe-version", required=True)
    p.add_argument("--preprocessing-version", required=True)
    p.add_argument("--tokenizer-version", required=True)
    p.add_argument("--output-parser-version", required=True)
    p.add_argument("--output", required=True, help="Destination .lcocr path.")
    p.add_argument("--component", default="", help="Component role for a component package.")
    p.add_argument("--quantize", choices=["none", "fp16", "bf16", "int4-symmetric", "int4-asymmetric", "int8"],
                   default="none",
                   help="Storage/quantization for tensors (explicit opt-in). fp16/bf16 are "
                        "dense storage conversions; int4/int8 are grouped quantization.")
    p.add_argument("--group-size", type=int, default=128, choices=[64, 128])
    p.add_argument("--transpose-linear", action="store_true",
                   help="Transpose [N,K] linear weights to canonical [K,N] (mathematically valid only).")
    p.add_argument("--producer-version", default="1.0.0")
    return p


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    if not args.license.strip():
        _die("--license must be a non-empty SPDX identifier")
    if not args.revision.strip():
        _die("--revision must be a non-empty exact revision")
    checkpoint_dir = args.checkpoint_dir
    if not os.path.isdir(checkpoint_dir):
        _die(f"checkpoint dir not found: {checkpoint_dir}")
    config_path = _require_local_file(args.config, "official config")
    config = _load_official_config(config_path)
    config_fingerprint = hashlib.sha256(
        json.dumps(config, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()

    try:
        from safetensors import safe_open  # type: ignore
    except ImportError:
        _die("safetensors is required for real checkpoints (pip install safetensors); "
             "synthetic fixtures use the standard-library generator instead")

    shard_paths = sorted(
        os.path.join(checkpoint_dir, f)
        for f in os.listdir(checkpoint_dir)
        if f.endswith(".safetensors")
    )
    if not shard_paths:
        _die(f"no .safetensors shards found in {checkpoint_dir}")

    source_hashes = [
        {"path": os.path.basename(p), "algorithm": "sha256", "digest": _sha256_file(p)}
        for p in shard_paths
    ]
    source_hashes.append(
        {"path": os.path.basename(config_path), "algorithm": "sha256", "digest": _sha256_file(config_path)}
    )

    writer = PackageWriter(args.output)
    seen_names = set()
    tensor_total = 0
    for shard in shard_paths:
        # safe_open is lazy: tensors are materialized one at a time, never as a
        # whole-model dictionary.
        with safe_open(shard, framework="np") as handle:
            for name in handle.keys():
                if name in seen_names:
                    _die(f"duplicate tensor across shards: {name}")
                seen_names.add(name)
                tensor = handle.get_tensor(name)  # numpy array, single tensor
                canonical = name  # name canonicalization hook (identity by default)
                shape = list(tensor.shape)
                layout = LAYOUT_ROW_MAJOR
                if args.transpose_linear and tensor.ndim == 2 and name.endswith(".weight"):
                    tensor = tensor.T.copy()
                    shape = list(tensor.shape)
                    layout = LAYOUT_KN
                encoding = ENCODING_FP32
                quant_kind = QUANT_NONE
                group_size = 0
                scales, zero_points = [], []
                if args.quantize == "none":
                    payload = tensor.astype("<f4").tobytes()
                elif args.quantize == "fp16":
                    payload = _fp32_to_fp16_bytes(tensor)
                    encoding = ENCODING_FP16
                elif args.quantize == "bf16":
                    payload = _fp32_to_bf16_bytes(tensor)
                    encoding = ENCODING_BF16
                elif args.quantize == "int4-symmetric":
                    payload, scales, zero_points = _quantize_int4(tensor, args.group_size, True)
                    encoding, quant_kind, group_size = ENCODING_INT4_PACKED, QUANT_INT4_SYMMETRIC, args.group_size
                elif args.quantize == "int4-asymmetric":
                    payload, scales, zero_points = _quantize_int4(tensor, args.group_size, False)
                    encoding, quant_kind, group_size = ENCODING_INT4_PACKED, QUANT_INT4_ASYMMETRIC, args.group_size
                else:  # int8
                    payload, scales = _quantize_int8(tensor, args.group_size)
                    encoding, quant_kind, group_size = ENCODING_INT8, QUANT_INT8_SYMMETRIC, args.group_size
                writer.add_tensor(canonical, encoding, layout, shape, payload,
                                  quant_kind=quant_kind, group_size=group_size,
                                  scales=scales, zero_points=zero_points)
                tensor_total += 1
                del tensor  # release before the next tensor

    manifest = {
        "format_version": 1,
        "model": args.model,
        "recipe_version": args.recipe_version,
        "checkpoint_revision": args.revision,
        "config_fingerprint": config_fingerprint,
        "license": args.license,
        "producer": "pack_model.py",
        "producer_version": args.producer_version,
        "preprocessing_version": args.preprocessing_version,
        "tokenizer_version": args.tokenizer_version,
        "output_parser_version": args.output_parser_version,
        "component": args.component,
        "dependencies": [],
        "source_hashes": source_hashes,
    }
    writer.finish(manifest)
    print(f"pack_model: wrote {tensor_total} tensors to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())