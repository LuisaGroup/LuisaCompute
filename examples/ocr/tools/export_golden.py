#!/usr/bin/env python3
"""export_golden.py -- export layered golden references from official models.

Offline tool. Builds golden artifacts around an EXPLICIT local official
implementation with forward hooks and deterministic greedy generation. Every
golden records the source checkpoint/tool revisions, tensor shape/layout/dtype
and the production decoding settings. Goldens are NEVER regenerated by tests;
this tool is the only writer and requires an explicit output path.

The official model/processor (torch/transformers) is imported lazily and only
when present; nothing is downloaded. The frozen SYNTHETIC goldens under
src/tests/data/ocr are produced by the standard-library generator and are
clearly labeled synthetic in golden_manifest.json -- they are NOT official
model outputs and this tool does not claim otherwise.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys


def _die(msg: str):
    print(f"export_golden: error: {msg}", file=sys.stderr)
    raise SystemExit(2)


def _sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="export_golden.py",
        description="Export layered golden references from an explicit local official model (offline).",
    )
    p.add_argument("--model-dir", required=True,
                   help="Local official model directory (weights + config + code; no download).")
    p.add_argument("--revision", required=True, help="Exact official checkpoint revision (recorded).")
    p.add_argument("--processor-dir", default="",
                   help="Local official processor directory (defaults to --model-dir).")
    p.add_argument("--input", required=True, help="Local input image/page for the golden.")
    p.add_argument("--output-dir", required=True, help="Destination directory for golden artifacts.")
    p.add_argument("--max-new-tokens", type=int, default=64,
                   help="Deterministic greedy generation length.")
    p.add_argument("--layers", default="preprocess,vision,decoder,logits,tokens",
                   help="Comma-separated golden layers to capture.")
    p.add_argument("--force", action="store_true",
                   help="Allow overwriting an existing golden directory (explicit opt-in).")
    return p


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    if not os.path.isdir(args.model_dir):
        _die(f"model dir not found: {args.model_dir} (offline; no implicit download)")
    if not os.path.isfile(args.input):
        _die(f"input not found: {args.input}")
    if os.path.exists(args.output_dir) and os.listdir(args.output_dir) and not args.force:
        _die(f"output dir not empty: {args.output_dir} (use --force to overwrite; goldens are never auto-regenerated)")
    try:
        import torch  # type: ignore
        from transformers import AutoModel, AutoProcessor  # type: ignore
    except ImportError:
        _die("torch/transformers are required for official golden export; "
             "install them locally (this tool never downloads them)")
    os.makedirs(args.output_dir, exist_ok=True)
    processor_dir = args.processor_dir or args.model_dir
    processor = AutoProcessor.from_pretrained(processor_dir, local_files_only=True)
    model = AutoModel.from_pretrained(args.model_dir, local_files_only=True)
    model.eval()

    # Deterministic decode settings recorded with every golden.
    decode_settings = {
        "greedy": True,
        "do_sample": False,
        "temperature": 0.0,
        "max_new_tokens": args.max_new_tokens,
        "torch_dtype": str(model.dtype),
    }
    captured = {}
    hooks = []

    def _hook(name):
        def fn(_module, _inputs, output):
            tensor = output[0] if isinstance(output, (tuple, list)) else output
            if hasattr(tensor, "detach"):
                captured[name] = tensor.detach().to(torch.float32).cpu()
        return fn

    # Register forward hooks on the requested layers (best-effort name match).
    wanted = {s.strip() for s in args.layers.split(",") if s.strip()}
    for name, module in model.named_modules():
        for layer in wanted:
            if layer in name and name not in captured:
                hooks.append(module.register_forward_hook(_hook(name)))
                break

    from PIL import Image  # type: ignore
    image = Image.open(args.input).convert("RGB")
    inputs = processor(images=image, return_tensors="pt")
    with torch.no_grad():
        generated = model.generate(**inputs, do_sample=False, max_new_tokens=args.max_new_tokens)
    tokens = generated[0].tolist()

    # Write golden tensors as raw float32 + a shape/layout/dtype sidecar.
    import numpy as np  # type: ignore
    tensor_meta = {}
    for name, tensor in captured.items():
        arr = tensor.numpy().astype("<f4")
        safe = name.replace(".", "_")
        bin_path = os.path.join(args.output_dir, f"{safe}.f32")
        arr.tofile(bin_path)
        tensor_meta[name] = {
            "file": f"{safe}.f32",
            "shape": list(arr.shape),
            "layout": "row_major",
            "dtype": "f32",
        }
    golden = {
        "format_version": 1,
        "kind": "official",  # NOT synthetic
        "model_revision": args.revision,
        "tool": "export_golden.py",
        "tool_version": "1.0.0",
        "source_input_hash": _sha256_file(args.input),
        "decode_settings": decode_settings,
        "tokens": tokens,
        "tensors": tensor_meta,
    }
    with open(os.path.join(args.output_dir, "golden.json"), "w", encoding="utf-8") as f:
        json.dump(golden, f, ensure_ascii=False, indent=2)
    for h in hooks:
        h.remove()
    print(f"export_golden: wrote {len(captured)} layer tensors + {len(tokens)} tokens to {args.output_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())